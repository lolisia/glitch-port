-- Projects and their public keys. Issues, events and labels now reference a
-- project through a cascading foreign key. The legacy messages table keeps its
-- project_id without a foreign key: old rows must stay readable even after
-- their project was deleted.

create table projects (
    id bigint generated by default as identity primary key,
    name text not null,
    slug text not null unique,
    platform text,
    created_at timestamptz not null default now()
);

create table project_keys (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects (id) on delete cascade,
    public_key text not null unique,
    label text,
    is_active boolean not null default true,
    rate_limit_per_minute integer check (rate_limit_per_minute is null or rate_limit_per_minute >= 0),
    created_at timestamptz not null default now(),
    revoked_at timestamptz
);

-- Data written before projects existed only carried a numeric project id, so
-- every id that is still referenced becomes a project of its own. Reusing the
-- id keeps the existing issues, events, labels and messages valid when the
-- foreign keys below are added.
insert into projects (id, name, slug)
select referenced.project_id,
       'Project ' || referenced.project_id,
       'project-' || referenced.project_id
from (
    select project_id from issues
    union
    select project_id from events
    union
    select project_id from labels
    union
    select project_id from messages
) as referenced
where not exists (select 1 from projects existing where existing.id = referenced.project_id)
order by referenced.project_id;

-- Explicit ids do not advance the identity sequence, so align it with the
-- highest id instead of letting the next generated id collide.
select setval(pg_get_serial_sequence('projects', 'id'), coalesce(max(id), 0) + 1, false) from projects;

alter table issues
    add constraint fk_issues_project_id
    foreign key (project_id) references projects (id) on delete cascade;

alter table events
    add constraint fk_events_project_id
    foreign key (project_id) references projects (id) on delete cascade;

alter table labels
    add constraint fk_labels_project_id
    foreign key (project_id) references projects (id) on delete cascade;
